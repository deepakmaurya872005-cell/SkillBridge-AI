import jsPDF from "jspdf";

export const generatePDF = (analysis) => {

    const doc = new jsPDF();

    let y = 20;

    doc.setFontSize(20);
    doc.text("SkillBridge AI Resume Report", 20, y);

    y += 15;

    doc.setFontSize(12);

    doc.text(`Target Job : ${analysis.targetJob}`, 20, y);
    y += 10;

    doc.text(`ATS Score : ${analysis.atsScore}%`, 20, y);
    y += 10;

    doc.text(`Skill Match : ${analysis.skillMatch}%`, 20, y);
    y += 10;

    doc.text(`Expected Package : ${analysis.packagePrediction}`, 20, y);

    y += 20;

    doc.setFontSize(16);
    doc.text("Existing Skills", 20, y);

    y += 10;

    doc.setFontSize(12);

    analysis.existingSkills.forEach(skill => {

        doc.text(`• ${skill}`, 25, y);

        y += 8;

    });

    y += 8;

    doc.setFontSize(16);

    doc.text("Missing Skills", 20, y);

    y += 10;

    doc.setFontSize(12);

    analysis.missingSkills.forEach(skill => {

        doc.text(`• ${skill}`, 25, y);

        y += 8;

    });

    y += 8;

    doc.setFontSize(16);

    doc.text("Recommendations", 20, y);

    y += 10;

    doc.setFontSize(12);

    analysis.recommendations.forEach(item => {

        doc.text(`• ${item}`, 25, y);

        y += 8;

    });

    y += 8;

    doc.setFontSize(16);

    doc.text("Resume Improvements", 20, y);

    y += 10;

    doc.setFontSize(12);

    analysis.improvements.forEach(item => {

        doc.text(`• ${item}`, 25, y);

        y += 8;

    });

    y += 8;

    doc.setFontSize(16);

    doc.text("Weaknesses", 20, y);

    y += 10;

    doc.setFontSize(12);

    analysis.weaknesses.forEach(item => {

        doc.text(`• ${item}`, 25, y);

        y += 8;

    });

    y += 20;

    doc.setFontSize(10);

    doc.text(
        "Generated by SkillBridge AI",
        20,
        y
    );

    doc.save("SkillBridge_AI_Report.pdf");

};